class EmbeddingGenerator:
    """
    A class to load pre-trained models and generate temporal, graph,
    and node embeddings for new, unseen daily data.
    """
    def __init__(self, temporal_model_path, graph_model_path, device=DEVICE):
        """
        Initializes the generator by loading pre-trained model weights.

        Args:
            temporal_model_path (str): Path to the .pth file for the temporal model.
            graph_model_path (str): Path to the .pth file for the graph model.
            device (torch.device): The device to run the models on (e.g., 'cpu' or 'cuda').
        """
        self.device = device
        print(f"Initializing EmbeddingGenerator on device: {self.device}")

        # Initialize model architectures
        # Note: The output_dim for the temporal decoder isn't used for inference,
        # so we can set it to a placeholder value like 24.
        self.temporal_model = TemporalSpreadVGAE(T_INPUT_DIM, T_HIDDEN_DIM, T_LATENT_DIM, 24).to(self.device)
        self.graph_model = DSENVGAE(NODE_FEATURE_DIM, G_EMBEDDING_DIM, G_LATENT_DIM, G_NUM_HAN_LAYERS, (NODE_TYPES, EDGE_TYPES)).to(self.device)

        # Load pre-trained weights
        self.temporal_model.load_state_dict(torch.load(temporal_model_path, map_location=self.device))
        self.graph_model.load_state_dict(torch.load(graph_model_path, map_location=self.device))

        # Set models to evaluation mode
        self.temporal_model.eval()
        self.graph_model.eval()

        print("Models loaded and set to evaluation mode successfully.")

    def _preprocess_temporal_data(self, timestamps):
        """
        Converts a list of timestamps (in minutes) into a feature tensor.
        """
        features = []
        prev_time = 0
        # Sort timestamps to ensure correct time difference calculation
        sorted_ts = sorted(timestamps)

        for t in sorted_ts:
            h, m = t // 60, t % 60
            # Features: sin/cos of hour, sin/cos of minute, normalized time delta
            features.append([
                sin(2 * pi * h / 24), cos(2 * pi * h / 24),
                sin(2 * pi * m / 60), cos(2 * pi * m / 60),
                (t - prev_time) / 1440.0
            ])
            prev_time = t

        # Pad the sequence to the maximum length
        padding_needed = T_MAX_SEQ_LEN - len(features)
        if padding_needed > 0:
            features.extend([[0.0] * T_INPUT_DIM for _ in range(padding_needed)])

        # Truncate if longer than max length
        features = features[:T_MAX_SEQ_LEN]

        return torch.tensor(features, dtype=torch.float32).unsqueeze(0) # Add batch dimension

    def _finalize_graph(self, graph_data):
        """
        Ensures a HeteroData object has all required node and edge types defined,
        even if they are empty, to prevent errors in the graph model.
        """
        for n_type in NODE_TYPES:
            if n_type not in graph_data.node_types:
                # Add an empty tensor with the correct feature dimension
                graph_data[n_type].x = torch.empty((0, NODE_FEATURE_DIM), dtype=torch.float)

        for e_type in EDGE_TYPES:
            if e_type not in graph_data.edge_types:
                # Add an empty edge index tensor
                graph_data[e_type].edge_index = torch.empty((2, 0), dtype=torch.long)
        return graph_data

    @torch.no_grad()
    def get_embeddings(self, timestamps, graph_data):
        """
        Computes all embeddings for a given set of timestamps and a graph.

        Args:
            timestamps (list[int]): A list of event timestamps in minutes from midnight (e.g., [540, 555, 720]).
            graph_data (torch_geometric.data.HeteroData): The graph for the day.

        Returns:
            dict: A dictionary containing the following embeddings:
                  - 'temporal_embedding': (np.array)
                  - 'graph_embedding': (np.array)
                  - 'aggregate_embedding': (np.array)
                  - 'node_embeddings': (dict of np.array)
        """
        # 1. Preprocess and get temporal embedding
        temporal_input = self._preprocess_temporal_data(timestamps).to(self.device)
        temporal_mu, _ = self.temporal_model.encode(temporal_input)

        # 2. Preprocess and get graph and node embeddings
        finalized_graph = self._finalize_graph(graph_data).to(self.device)
        graph_mu, _, node_embs_dict = self.graph_model.encode(finalized_graph)

        # FIX: The temporal model outputs a 2D tensor [1, latent_dim] while the
        # graph model outputs a 1D tensor [latent_dim]. We add a batch dimension
        # to the graph embedding to make them compatible for concatenation.
        if graph_mu.dim() == 1:
            graph_mu = graph_mu.unsqueeze(0)

        # 3. Combine graph and temporal embeddings
        aggregate_emb = torch.cat([temporal_mu, graph_mu], dim=1)

        # 4. Convert all tensors to numpy arrays for easy use
        results = {
            "temporal_embedding": temporal_mu.cpu().numpy().flatten(),
            "graph_embedding": graph_mu.cpu().numpy().flatten(),
            "aggregate_embedding": aggregate_emb.cpu().numpy().flatten(),
            "node_embeddings": {nt: emb.cpu().numpy() for nt, emb in node_embs_dict.items()}
        }

        return results


