class DSENVGAE(nn.Module):
    def __init__(self, n, e, l, n_layers, meta):
        super().__init__(); self.latent_dim, self.metadata = l, meta; self.lin_dict = nn.ModuleDict({nt: nn.Linear(n,e) for nt in meta[0]}); self.han_convs = nn.ModuleList([HANConv(e,e,metadata=meta,heads=4) for _ in range(n_layers)]); self.mu_linear, self.logvar_linear = nn.Linear(e,l), nn.Linear(e,l)
    def encode(self, data):
        x_dict = {nt: self.lin_dict[nt](x) for nt, x in data.x_dict.items()}; [x_dict := conv(x_dict, data.edge_index_dict) for conv in self.han_convs]
        pooled = [x.mean(dim=0) for x in x_dict.values() if x.size(0) > 0]; p_mean = torch.stack(pooled).mean(dim=0) if pooled else torch.zeros(G_EMBEDDING_DIM, device=DEVICE); return self.mu_linear(p_mean), self.logvar_linear(p_mean), x_dict
    def reparameterize(self, mu, logvar): std = torch.exp(0.5*logvar); eps = torch.randn_like(std); return mu+eps*std
    def decode(self, z, h_dict, edge_index_dict):
        loss, n_types = 0, 0
        for et, ei in edge_index_dict.items():
            if ei.numel() == 0: continue
            n_types+=1; st,_,dt=et; pos_src_idx,pos_dst_idx=ei[0],ei[1]; pos_src_emb,pos_dst_emb=h_dict[st][pos_src_idx],h_dict[dt][pos_dst_idx]; pos_score=(pos_src_emb*pos_dst_emb).sum(dim=-1)
            neg_dst_idx=torch.randint(0,h_dict[dt].size(0),(len(pos_dst_idx),),device=z.device); neg_dst_emb=h_dict[dt][neg_dst_idx]; neg_score=(pos_src_emb*neg_dst_emb).sum(dim=-1); loss+=-torch.log(torch.sigmoid(pos_score-neg_score)+1e-9).mean()
        return loss/(n_types+1e-9)
    def forward(self, data): return self.encode(data)
    def loss(self, mu, logvar, h_dict, orig_data, beta): z=self.reparameterize(mu,logvar); recon_loss=self.decode(z,h_dict,orig_data.edge_index_dict); kl_loss=-0.5*torch.sum(1+logvar-mu.pow(2)-logvar.exp()); return recon_loss+beta*kl_loss

