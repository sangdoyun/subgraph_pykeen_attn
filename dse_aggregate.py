# --- Temporal Spread Model ---
class TemporalDataset(Dataset):
    def __init__(self, daily_data, max_seq_len, num_hist_bins=24):
        self.daily_data = daily_data
        self.max_seq_len = max_seq_len
        self.num_hist_bins = num_hist_bins

    def __len__(self):
        return len(self.daily_data)

    def create_hourly_histogram(self, timestamps_minutes):
        hist, _ = np.histogram(timestamps_minutes, bins=np.linspace(0, 1440, self.num_hist_bins + 1))
        return hist / (np.sum(hist) + 1e-9)

    def __getitem__(self, idx):
        timestamps = self.daily_data[idx]
        features = []
        if timestamps:
            prev_time = 0
            for t in timestamps:
                hour, minute_of_hour = t // 60, t % 60
                features.append([
                    sin(2 * pi * hour / 24), cos(2 * pi * hour / 24),
                    sin(2 * pi * minute_of_hour / 60), cos(2 * pi * minute_of_hour / 60),
                    (t - prev_time) / 1440.0
                ])
                prev_time = t

        if len(features) > self.max_seq_len:
            features = features[:self.max_seq_len]
        else:
            features.extend([[0.0] * 5 for _ in range(self.max_seq_len - len(features))])

        histogram = self.create_hourly_histogram(timestamps)
        return torch.tensor(features, dtype=torch.float32), torch.tensor(histogram, dtype=torch.float32)

class TemporalSpreadVGAE(nn.Module):
    def __init__(self, input_dim, hidden_dim, latent_dim, output_dim, num_layers=2):
        super(TemporalSpreadVGAE, self).__init__()
        self.encoder_rnn = nn.LSTM(input_dim, hidden_dim, num_layers, batch_first=True, bidirectional=True)
        self.fc_mu = nn.Linear(hidden_dim * 2, latent_dim)
        self.fc_logvar = nn.Linear(hidden_dim * 2, latent_dim)
        self.decoder_fc = nn.Sequential(
            nn.Linear(latent_dim, hidden_dim), nn.ReLU(),
            nn.Linear(hidden_dim, output_dim), nn.Softmax(dim=-1)
        )

    def encode(self, x):
        _, (hidden, _) = self.encoder_rnn(x)
        hidden = torch.cat((hidden[-2,:,:], hidden[-1,:,:]), dim=1)
        return self.fc_mu(hidden), self.fc_logvar(hidden)

    def reparameterize(self, mu, logvar):
        std = torch.exp(0.5 * logvar)
        eps = torch.randn_like(std)
        return mu + eps * std

    def decode(self, z):
        return self.decoder_fc(z)

    def forward(self, x):
        mu, logvar = self.encode(x)
        z = self.reparameterize(mu, logvar)
        return self.decode(z), mu, logvar

# --- Whom/Where/Activity (Graph) Model ---
class DSENVGAE(nn.Module):
    def __init__(self, node_feature_dim, embedding_dim, latent_dim, num_layers, metadata):
        super(DSENVGAE, self).__init__()
        self.latent_dim = latent_dim
        self.metadata = metadata

        # Encoder
        self.lin_dict = nn.ModuleDict({
            node_type: nn.Linear(node_feature_dim, embedding_dim) for node_type in metadata[0]
        })
        self.han_convs = nn.ModuleList([
            HANConv(embedding_dim, embedding_dim, metadata=metadata, heads=4) for _ in range(num_layers)
        ])
        self.mu_linear = nn.Linear(embedding_dim, latent_dim)
        self.logvar_linear = nn.Linear(embedding_dim, latent_dim)

    def encode(self, data):
        x_dict = {
            node_type: self.lin_dict[node_type](x) for node_type, x in data.x_dict.items()
        }
        for conv in self.han_convs:
            x_dict = conv(x_dict, data.edge_index_dict)

        # Mean pooling across all nodes of all types to get graph embedding
        pooled_embeddings = [x.mean(dim=0) for x in x_dict.values() if x.size(0) > 0]
        if not pooled_embeddings:
            # Return zeros for an empty or invalid graph
            pooled_mean = torch.zeros(G_EMBEDDING_DIM, device=DEVICE)
        else:
            pooled_mean = torch.stack(pooled_embeddings).mean(dim=0)

        mu = self.mu_linear(pooled_mean)
        log_var = self.logvar_linear(pooled_mean)
        return mu, log_var, x_dict

    def reparameterize(self, mu, logvar):
        std = torch.exp(0.5 * logvar)
        eps = torch.randn_like(std)
        return mu + eps * std

    def decode(self, z, h_dict, edge_index_dict):
        """
        Calculates link reconstruction loss.
        z: The latent vector for the graph. Not directly used here, but part of VAE structure.
        h_dict: The dictionary of node embeddings from the encoder.
        edge_index_dict: The ground-truth edges of the graph.
        """
        link_recon_loss = 0
        num_edge_types_processed = 0

        # Iterate through the ground-truth edge types
        for edge_type, edge_index in edge_index_dict.items():
            if edge_index.numel() == 0:
                continue

            num_edge_types_processed += 1
            src_type, _, dst_type = edge_type

            # Get embeddings for the source and destination nodes of existing ("positive") edges
            pos_src_indices = edge_index[0]
            pos_dst_indices = edge_index[1]
            pos_src_embeds = h_dict[src_type][pos_src_indices]
            pos_dst_embeds = h_dict[dst_type][pos_dst_indices]

            # Calculate score for positive edges (dot product similarity)
            pos_score = (pos_src_embeds * pos_dst_embeds).sum(dim=-1)

            # Negative sampling: randomly sample destination nodes
            num_dst_nodes_total = h_dict[dst_type].size(0)
            neg_dst_indices = torch.randint(0, num_dst_nodes_total, (len(pos_dst_indices),), device=z.device)
            neg_dst_embeds = h_dict[dst_type][neg_dst_indices]

            neg_score = (pos_src_embeds * neg_dst_embeds).sum(dim=-1)

            # Using Binary Positive-unlabeled (BPR) loss as a simple and effective choice
            loss = -torch.log(torch.sigmoid(pos_score - neg_score) + 1e-9).mean()
            link_recon_loss += loss

        # Average the loss over the number of edge types present in the graph
        return link_recon_loss / (num_edge_types_processed + 1e-9)

    def forward(self, data):
        # The forward pass runs the encoder to get latent variables and node embeddings
        mu, logvar, h_dict = self.encode(data)
        return mu, logvar, h_dict

    def loss(self, mu, logvar, h_dict, original_data, beta):
        """
        Calculates the total loss for the VAE.
        """
        # Reparameterize to get the latent vector z
        z = self.reparameterize(mu, logvar)

        # Calculate the reconstruction loss by calling the decoder
        # The decoder now receives the correct dictionaries it needs
        link_recon_loss = self.decode(z, h_dict, original_data.edge_index_dict)

        # Calculate the KL Divergence
        kl_loss = -0.5 * torch.sum(1 + logvar - mu.pow(2) - logvar.exp())

        # Combine the losses
        total_loss = link_recon_loss + beta * kl_loss
        return total_loss

# --- 4. Training and Evaluation ---

def train_temporal_model(data, epochs):
    print("\n--- Training Temporal Spread VAE ---")
    dataset = TemporalDataset(data, T_MAX_SEQ_LEN, T_NUM_HIST_BINS)
    dataloader = DataLoader(dataset, batch_size=32, shuffle=True)
    model = TemporalSpreadVGAE(T_INPUT_DIM, T_HIDDEN_DIM, T_LATENT_DIM, T_NUM_HIST_BINS).to(DEVICE)
    optimizer = torch.optim.Adam(model.parameters(), lr=0.001)
    recon_loss_fn = nn.KLDivLoss(reduction='batchmean')

    model.train()
    for epoch in range(epochs):
        total_loss = 0
        for features, histograms in tqdm(dataloader, desc=f"Epoch {epoch+1}/{epochs}"):
            features, histograms = features.to(DEVICE), histograms.to(DEVICE)
            optimizer.zero_grad()
            recon_hist, mu, logvar = model(features)

            recon_loss = recon_loss_fn(torch.log(recon_hist + 1e-9), histograms)
            kl_loss = -0.5 * torch.sum(1 + logvar - mu.pow(2) - logvar.exp())

            loss = recon_loss + BETA_KL * kl_loss / features.size(0) # Normalize KL by batch size
            loss.backward()
            optimizer.step()
            total_loss += loss.item()
    print(f"Temporal VAE training complete. Final Loss: {total_loss / len(dataloader):.4f}")
    return model

def train_graph_model(data, epochs):
    print("\n--- Training Social/Activity (Graph) VAE ---")
    metadata = (NODE_TYPES, EDGE_TYPES)
    model = DSENVGAE(NODE_FEATURE_DIM, G_EMBEDDING_DIM, G_LATENT_DIM, G_NUM_HAN_LAYERS, metadata).to(DEVICE)
    optimizer = torch.optim.Adam(model.parameters(), lr=0.001)

    model.train()
    for epoch in range(epochs):
        total_loss = 0
        # Training one graph at a time for simplicity
        for graph_data in tqdm(data, desc=f"Epoch {epoch+1}/{epochs}"):
            graph_data = graph_data.to(DEVICE)
            optimizer.zero_grad()
            mu, logvar, h_dict = model(graph_data)
            loss = model.loss(mu, logvar, h_dict, graph_data, BETA_KL)
            if torch.isnan(loss): continue # Skip if loss becomes NaN (can happen with unstable graphs)
            loss.backward()
            optimizer.step()
            total_loss += loss.item()
    print(f"Graph VAE training complete. Final Loss: {total_loss / len(data):.4f}")
    return model

def get_embeddings(temporal_model, graph_model, temporal_data, graph_data):
    print("\n--- Extracting and Aggregating Embeddings ---")
    temporal_model.eval()
    graph_model.eval()

    all_temporal_embeddings = []
    all_graph_embeddings = []

    # Using the same Dataset class for temporal data to ensure consistent preprocessing
    temporal_dataset = TemporalDataset(temporal_data, T_MAX_SEQ_LEN, T_NUM_HIST_BINS)

    with torch.no_grad():
        # Get temporal embeddings
        for i in range(len(temporal_dataset)):
            features, _ = temporal_dataset[i]
            features = features.unsqueeze(0).to(DEVICE) # Add batch dimension
            mu, _ = temporal_model.encode(features)
            all_temporal_embeddings.append(mu.cpu().numpy().flatten())

        # Get graph embeddings
        for g_data in tqdm(graph_data, desc="Extracting Graph Embeddings"):
            g_data = g_data.to(DEVICE)
            mu, _ , _ = graph_model.encode(g_data)
            all_graph_embeddings.append(mu.cpu().numpy().flatten())

    # Aggregate by concatenation
    agg_embeddings = np.concatenate([
        np.array(all_temporal_embeddings),
        np.array(all_graph_embeddings)
    ], axis=1)

    return agg_embeddings

