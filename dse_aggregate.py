def train_temporal_model(data, epochs):
    print("\n--- Training Temporal Spread VAE ---")
    dataset = TemporalDataset(data); loader = DataLoader(dataset, batch_size=32, shuffle=True)
    model = TemporalSpreadVGAE(T_INPUT_DIM, T_HIDDEN_DIM, T_LATENT_DIM, T_NUM_HIST_BINS).to(DEVICE)
    optimizer = torch.optim.Adam(model.parameters(), lr=0.001)
    for epoch in range(epochs):
        for features, histograms in tqdm(loader, desc=f"Temporal Epoch {epoch+1}/{epochs}", leave=False):
            features, histograms = features.to(DEVICE), histograms.to(DEVICE); optimizer.zero_grad()
            recon_hist, mu, logvar = model(features); recon_loss = F.kl_div(torch.log(recon_hist + 1e-9), histograms, reduction='batchmean'); kl_loss = -0.5 * torch.sum(1 + logvar - mu.pow(2) - logvar.exp()); loss = recon_loss + BETA_KL * kl_loss / features.size(0); loss.backward(); optimizer.step()
    return model

def train_graph_model(data, epochs):
    print("--- Training Social/Activity (Graph) VAE ---")
    metadata = (NODE_TYPES, EDGE_TYPES)
