def random_date(start, end):
    delta = end - start
    rand_days = random.randint(0, delta.days)
    rand_seconds = random.randint(0, 86400)
    return start + timedelta(days=rand_days, seconds=rand_seconds)

def generate_tpp_timestamps(start_date, end_date, intensity=0.1):
    total_days = (end_date - start_date).days
    timestamps = []
    current = start_date
    while current < end_date:
        interval = np.random.exponential(1.0 / intensity)
        current += timedelta(hours=interval * 24)
        if current < end_date:
            timestamps.append(current)
    return timestamps

def simulate_travel(user_id):
    travel_phases, images, app_usages = [], [], []
    for i in range(2):
        travel_start = random_date(START_DATE, END_DATE - timedelta(days=7))
        travel_end = travel_start + timedelta(days=random.randint(3, 7))
        city = random.choice(LOCATIONS)
        scene = random.choice(['beach', 'market', 'temple', 'hiking trail'])
        images.append({
            'user_id': user_id, 'person_id': str(uuid.uuid4()), 'gender': random.choice(['M', 'F']),
            'age': random.randint(20, 50), 'bounding_box': [random.randint(0, 300), random.randint(0, 300), 50, 50],
            'timestamp': travel_start.isoformat(), 'location': city, 'scene_name': scene
        })
        for _ in range(random.randint(10, 25)):
            images.append({
                'user_id': user_id, 'person_id': None, 'gender': None, 'age': None,
                'bounding_box': None, 'timestamp': (travel_start + timedelta(hours=random.randint(0, 120))).isoformat(),
                'location': city, 'scene_name': random.choice(SCENE_NAMES)
            })
        for _ in range(random.randint(20, 50)):
            app_usages.append({
                'user_id': user_id, 'timestamp': (travel_start + timedelta(hours=random.randint(0, 120))).isoformat(),
                'duration': random.randint(30, 600), 'package_name': random.choice(APP_PACKAGES),
                'event_type': random.choice(['foreground', 'background']), 'time_zone': 'UTC+0'
            })
        travel_phases.append({
            'user_id': user_id, 'start_date': travel_start.isoformat(),
            'end_date': travel_end.isoformat(), 'city': city
        })
    return travel_phases, images, app_usages

def simulate_interest_change(user_id):
    interest_events, interest_images, interest_apps = [], [], []
    interest_day = random_date(START_DATE, END_DATE - timedelta(days=30))
    new_interest = random.choice(list(INTEREST_APPS.keys()))
    trigger_app = random.choice(INTEREST_APPS[new_interest])
    interest_apps.append({
        'user_id': user_id, 'timestamp': interest_day.isoformat(), 'duration': random.randint(60, 300),
        'package_name': trigger_app, 'event_type': 'foreground', 'time_zone': 'UTC+0'
    })
    for _ in range(random.randint(30, 60)):
        interest_apps.append({
            'user_id': user_id, 'timestamp': (interest_day + timedelta(hours=random.randint(0, 240))).isoformat(),
            'duration': random.randint(30, 600), 'package_name': random.choice(INTEREST_APPS[new_interest]),
            'event_type': 'foreground', 'time_zone': 'UTC+0'
        })
    for _ in range(random.randint(5, 15)):
        interest_images.append({
            'user_id': user_id, 'person_id': None, 'gender': None, 'age': None,
            'bounding_box': None, 'timestamp': (interest_day + timedelta(hours=random.randint(0, 240))).isoformat(),
            'location': random.choice(LOCATIONS), 'scene_name': new_interest
        })
    interest_events.append({
        'user_id': user_id, 'interest': new_interest,
        'start_date': interest_day.isoformat(), 'phase': 'growth'
    })
    return interest_events, interest_images, interest_apps

def simulate_normal_data(user_id):
    timestamps = generate_tpp_timestamps(START_DATE, END_DATE, intensity=0.05)
    app_usages = [{
        'user_id': user_id, 'timestamp': t.isoformat(), 'duration': random.randint(20, 300),
        'package_name': random.choice(APP_PACKAGES), 'event_type': random.choice(['foreground', 'background']),
        'time_zone': 'UTC+0'
    } for t in timestamps]
    call_logs = [{
        'user_id': user_id, 'identifier': str(uuid.uuid4()), 'date': t.isoformat(),
        'type': random.choice(['incoming', 'outgoing', 'missed']), 'geocoded_loc': random.choice(LOCATIONS),
        'duration': random.randint(10, 600), 'number': f'+1{random.randint(1000000000, 9999999999)}',
        'contact_id': str(uuid.uuid4()), 'call_rec': None, 'call_rec_transcript': None,
        'ai_summary': None, 'ai_keywords': random.sample(['project', 'meeting', 'personal', 'urgent'], 2),
        'entities': random.sample(CONTACT_NAMES, 2)
    } for t in timestamps]
    return app_usages, call_logs

