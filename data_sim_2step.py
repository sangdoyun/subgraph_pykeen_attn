def generate_location_with_metadata():
    cities_info = [
        ("New York", "NY", "USA", 40.7128, -74.0060),
        ("San Francisco", "CA", "USA", 37.7749, -122.4194),
        ("Paris", "IDF", "France", 48.8566, 2.3522),
        ("Tokyo", "Tokyo", "Japan", 35.6895, 139.6917),
        ("London", "ENG", "UK", 51.5074, -0.1278),
        ("Berlin", "BE", "Germany", 52.5200, 13.4050),
        ("Mumbai", "MH", "India", 19.0760, 72.8777),
        ("Sydney", "NSW", "Australia", -33.8688, 151.2093)
    ]
    city, state, country, lat, lon = random.choice(cities_info)
    return {
        'lat': round(lat + random.uniform(-0.01, 0.01), 6),
        'lon': round(lon + random.uniform(-0.01, 0.01), 6),
        'city': city,
        'state': state,
        'country': country
    }

# Modify df_images location field
