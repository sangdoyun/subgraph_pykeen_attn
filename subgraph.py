class TemporalSpreadVGAE(nn.Module):
    """
    Temporal Variational Graph Autoencoder for time-series data.
    Encodes a sequence of events into a latent vector.
    """
    def __init__(self, input_dim, hidden_dim, latent_dim, output_dim, num_layers=2):
        super().__init__()
        self.encoder_rnn = nn.LSTM(input_dim, hidden_dim, num_layers, batch_first=True, bidirectional=True)
        self.fc_mu = nn.Linear(hidden_dim * 2, latent_dim)
        self.fc_logvar = nn.Linear(hidden_dim * 2, latent_dim)
        # Decoder is not needed for embedding generation, but included for completeness
        self.decoder_fc = nn.Sequential(
            nn.Linear(latent_dim, hidden_dim),
            nn.ReLU(),
            nn.Linear(hidden_dim, output_dim),
            nn.Softmax(dim=-1)
        )

    def encode(self, x):
        _, (h, _) = self.encoder_rnn(x)
        # Concatenate the final hidden states from both directions
        h_concat = torch.cat((h[-2,:,:], h[-1,:,:]), dim=1)
        mu = self.fc_mu(h_concat)
        logvar = self.fc_logvar(h_concat)
        return mu, logvar

    def forward(self, x):
        # For inference, we only need the encoding part.
        mu, _ = self.encode(x)
        return mu

class DSENVGAE(nn.Module):
    """
    Dynamic Social Entity Network VGAE for heterogeneous graphs.
    Encodes a graph's structure and node features into a latent vector
    and produces embeddings for each node.
    """
    def __init__(self, node_feat_dim, embed_dim, latent_dim, num_han_layers, metadata):
        super().__init__()
        self.latent_dim = latent_dim
        self.metadata = metadata

        # Linear projection for each node type
        self.lin_dict = nn.ModuleDict({
            nt: nn.Linear(node_feat_dim, embed_dim) for nt in metadata[0]
        })

        # Heterogeneous Graph Attention Layers
        self.han_convs = nn.ModuleList([
            HANConv(embed_dim, embed_dim, metadata=metadata, heads=4) for _ in range(num_han_layers)
        ])

        # Output layers for graph-level embedding
        self.mu_linear = nn.Linear(embed_dim, latent_dim)
        self.logvar_linear = nn.Linear(embed_dim, latent_dim)

    def encode(self, data):
        # Project node features into a common embedding space
        x_dict = {nt: self.lin_dict[nt](x) for nt, x in data.x_dict.items()}

        # Process through HAN layers
        for conv in self.han_convs:
            x_dict = conv(x_dict, data.edge_index_dict)

        # Pool node embeddings to get a graph-level representation
        # We only pool from node types that actually have nodes in the graph
        pooled_embs = [x.mean(dim=0) for x in x_dict.values() if x.size(0) > 0]

        if pooled_embs:
            graph_level_emb = torch.stack(pooled_embs).mean(dim=0)
        else:
            # Handle empty graphs
            graph_level_emb = torch.zeros(self.mu_linear.in_features, device=next(self.parameters()).device)

        mu = self.mu_linear(graph_level_emb)
        logvar = self.logvar_linear(graph_level_emb)

        # Return graph-level latent variables and node-level embeddings
        return mu, logvar, x_dict

    def forward(self, data):
        # For inference, we only need the encoding part.
        mu, _, node_embeddings = self.encode(data)
        return mu, node_embeddings


