# --- 1.2. Model Architecture Definitions ---
class TemporalSpreadVGAE(nn.Module):
    def __init__(self, input_dim, hidden_dim, latent_dim, output_dim, num_layers=2):
        super().__init__()
        self.encoder_rnn = nn.LSTM(input_dim, hidden_dim, num_layers, batch_first=True, bidirectional=True)
        self.fc_mu = nn.Linear(hidden_dim * 2, latent_dim)
        self.fc_logvar = nn.Linear(hidden_dim * 2, latent_dim)
    def encode(self, x):
        _, (h, _) = self.encoder_rnn(x)
        h_concat = torch.cat((h[-2,:,:], h[-1,:,:]), dim=1)
        return self.fc_mu(h_concat), self.fc_logvar(h_concat)
    def forward(self, x):
        mu, _ = self.encode(x)
        return mu

class DSENVGAE(nn.Module):
    def __init__(self, node_feat_dim, embed_dim, latent_dim, num_han_layers, metadata):
        super().__init__()
        self.lin_dict = nn.ModuleDict({nt: nn.Linear(node_feat_dim, embed_dim) for nt in metadata[0]})
        self.han_convs = nn.ModuleList([HANConv(embed_dim, embed_dim, metadata=metadata, heads=4) for _ in range(num_han_layers)])
        self.mu_linear = nn.Linear(embed_dim, latent_dim)
        self.logvar_linear = nn.Linear(embed_dim, latent_dim)
    def encode(self, data):
        x_dict = {nt: self.lin_dict[nt](x) for nt, x in data.x_dict.items()}
        for conv in self.han_convs:
            x_dict = conv(x_dict, data.edge_index_dict)
        pooled_embs = [x.mean(dim=0) for x in x_dict.values() if x.size(0) > 0]
        graph_level_emb = torch.stack(pooled_embs).mean(dim=0) if pooled_embs else torch.zeros(self.mu_linear.in_features, device=next(self.parameters()).device)
        return self.mu_linear(graph_level_emb), self.logvar_linear(graph_level_emb), x_dict
    def forward(self, data):
        mu, _, node_embeddings = self.encode(data)
        return mu, node_embeddings

# --- 1.3. Reusable Embedding Generator Class ---
class EmbeddingGenerator:
    def __init__(self, temporal_model_path, graph_model_path, device=DEVICE):
        self.device = device
        self.temporal_model = TemporalSpreadVGAE(T_INPUT_DIM, T_HIDDEN_DIM, T_LATENT_DIM, 24).to(self.device)
        self.graph_model = DSENVGAE(NODE_FEATURE_DIM, G_EMBEDDING_DIM, G_LATENT_DIM, G_NUM_HAN_LAYERS, (NODE_TYPES, EDGE_TYPES)).to(self.device)
        self.temporal_model.load_state_dict(torch.load(temporal_model_path, map_location=self.device))
        self.graph_model.load_state_dict(torch.load(graph_model_path, map_location=self.device))
        self.temporal_model.eval()
        self.graph_model.eval()
    def _preprocess_temporal_data(self, timestamps):
        features = []
        prev_time = 0
        for t in sorted(timestamps):
            h, m = t // 60, t % 60
            features.append([sin(2 * pi * h / 24), cos(2 * pi * h / 24), sin(2 * pi * m / 60), cos(2 * pi * m / 60), (t - prev_time) / 1440.0])
            prev_time = t
        padding_needed = T_MAX_SEQ_LEN - len(features)
        if padding_needed > 0: features.extend([[0.0] * T_INPUT_DIM for _ in range(padding_needed)])
        return torch.tensor(features[:T_MAX_SEQ_LEN], dtype=torch.float32).unsqueeze(0)
    def _finalize_graph(self, graph_data):
        for n_type in NODE_TYPES:
            if n_type not in graph_data.node_types: graph_data[n_type].x = torch.empty((0, NODE_FEATURE_DIM), dtype=torch.float)
        for e_type in EDGE_TYPES:
            if e_type not in graph_data.edge_types: graph_data[e_type].edge_index = torch.empty((2, 0), dtype=torch.long)
        return graph_data
    @torch.no_grad()
    def get_embeddings(self, timestamps, graph_data):
        temporal_input = self._preprocess_temporal_data(timestamps).to(self.device)
        temporal_mu, _ = self.temporal_model.encode(temporal_input)
        finalized_graph = self._finalize_graph(graph_data).to(self.device)
        graph_mu, _, node_embs_dict = self.graph_model.encode(finalized_graph)
        if graph_mu.dim() == 1: graph_mu = graph_mu.unsqueeze(0)
        aggregate_emb = torch.cat([temporal_mu, graph_mu], dim=1)
        return {"graph_embedding": graph_mu.cpu().numpy().flatten()}

