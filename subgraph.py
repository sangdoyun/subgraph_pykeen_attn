class StrategyGraphFeature(TrendAnalysisStrategy):
    def __init__(self):
        super().__init__("Graph Feature Trajectory")

    def _get_feature_vectors(self, graphs: List[nx.Graph]) -> List[np.ndarray]:
        # FIX: Create a consistent vocabulary of nodes for the entire sequence
        vocab = sorted(list(set(node for g in graphs for node in g.nodes())))
        node_to_idx = {node: i for i, node in enumerate(vocab)}

        vectors = []
        for g in graphs:
            vec = np.zeros(len(vocab))
            for node in g.nodes():
                if node in node_to_idx:
                    vec[node_to_idx[node]] = g.degree(node)
            norm = np.linalg.norm(vec)
            vectors.append(vec / norm if norm > 0 else vec)
        return vectors

    def analyze(self, graphs: List[nx.Graph]) -> str:
        if len(graphs) < 2: return "Insufficient Data"
        embeddings = self._get_feature_vectors(graphs)
        distances = [np.linalg.norm(e1 - e2) for e1, e2 in zip(embeddings, embeddings[1:])]
        avg_dist = np.mean(distances)

        if avg_dist < 0.2: return "Stable"
        if avg_dist > 0.9: return "Shifting" # Large distance means structure is fundamentally different

        # Check size trend if not clearly stable or shifting
        nodes = [g.number_of_nodes() for g in graphs]
        slope, _, _, _, _ = linregress(list(range(len(graphs))), nodes)
        norm_slope = slope / np.mean(nodes) if np.mean(nodes) > 0 else 0
        if norm_slope > 0.05: return "Growing"
        if norm_slope < -0.05: return "Decaying"
        return "Volatile"

