def group_subgraphs_by_activity(folder_path: str) -> Dict[str, List[Tuple[datetime, nx.Graph]]]:
    """
    Scans a directory for .gml files and groups them by anchor.
    Filenames are expected in the format 'YYYY-MM-DD_anchor_N.gml'.

    Args:
        folder_path: The path to the directory containing subgraph files.

    Returns:
        A dictionary where keys are anchor IDs (e.g., 'anchor_1') and
        values are lists of (timestamp, graph) tuples, sorted by timestamp.
    """
    if not os.path.isdir(folder_path):
        print(f"Error: Directory not found at '{folder_path}'")
        return {}

    activities = {}
    for filename in os.listdir(folder_path):
        if not filename.endswith(".gml"):
            continue

        # Regex to parse 'YYYY-MM-DD_anchor_N.gml'
        match = re.match(r"(\d{4}-\d{2}-\d{2})_(anchor_\d+)\.gml", filename)
        if not match:
            continue

        date_str, anchor_id = match.groups()
        try:
            timestamp = datetime.strptime(date_str, "%Y-%m-%d")
            graph_path = os.path.join(folder_path, filename)
            graph = nx.read_gml(graph_path, label='id') # Use 'id' if nodes are strings

            if anchor_id not in activities:
                activities[anchor_id] = []
            activities[anchor_id].append((timestamp, graph))

        except (ValueError, nx.NetworkXError) as e:
            print(f"Warning: Could not process file '{filename}'. Reason: {e}")
            continue

    # Sort each activity's graphs by date
    for anchor_id in activities:
        activities[anchor_id].sort(key=lambda x: x[0])

    return activities

def calculate_graph_similarity(g1: nx.Graph, g2: nx.Graph) -> Tuple[float, float]:
    """
    Calculates the Jaccard similarity for nodes and edges between two graphs.

    Returns:
        A tuple containing (node_jaccard_similarity, edge_jaccard_similarity).
    """
    nodes1 = set(g1.nodes())
    nodes2 = set(g2.nodes())

    # Create sets of edges (as sorted tuples to be canonical)
    edges1 = set(tuple(sorted(edge)) for edge in g1.edges())
    edges2 = set(tuple(sorted(edge)) for edge in g2.edges())

    node_intersection = len(nodes1.intersection(nodes2))
    node_union = len(nodes1.union(nodes2))
    node_jaccard = node_intersection / node_union if node_union > 0 else 0

    edge_intersection = len(edges1.intersection(edges2))
    edge_union = len(edges1.union(edges2))
    edge_jaccard = edge_intersection / edge_union if edge_union > 0 else 0

    return node_jaccard, edge_jaccard

def analyze_activity_trend(
    graphs: List[nx.Graph],
    growth_threshold: float = 0.15,
    decay_threshold: float = -0.15,
    stability_jaccard_threshold: float = 0.7
) -> str:
    """
    Analyzes a sequence of graphs to determine its trend.

    Args:
        graphs: A list of NetworkX graphs, sorted chronologically.
        growth_threshold: The average percentage increase in size to be considered 'Growing'.
        decay_threshold: The average percentage decrease in size to be considered 'Decaying'.
        stability_jaccard_threshold: The minimum Jaccard similarity to be considered 'Stable'.

    Returns:
        A string classification: 'Growing', 'Decaying', 'Stable', 'Volatile', or 'Insufficient Data'.
    """
    if len(graphs) < 2:
        return "Insufficient Data"

    size_changes = []
    jaccard_similarities = []

    for i in range(len(graphs) - 1):
        g1, g2 = graphs[i], graphs[i+1]

        # Calculate size change (using number of nodes as the primary metric)
        size1 = g1.number_of_nodes()
        size2 = g2.number_of_nodes()
        if size1 > 0:
            change = (size2 - size1) / size1
            size_changes.append(change)

        # Calculate structural similarity
        node_jaccard, edge_jaccard = calculate_graph_similarity(g1, g2)
        # We use node similarity as the primary structural metric
        jaccard_similarities.append(node_jaccard)

    if not size_changes: # Handle case where first graph is empty
        return "Insufficient Data"

    avg_size_change = np.mean(size_changes)
    avg_jaccard_sim = np.mean(jaccard_similarities)

    print(f"    Metrics: Avg. Size Change: {avg_size_change:.2%}, Avg. Jaccard Sim: {avg_jaccard_sim:.2f}")

    # Classify based on the metrics
    if avg_size_change > growth_threshold:
        return "Growing"
    elif avg_size_change < decay_threshold:
        return "Decaying"
    else:
        # Size is relatively constant, now check if the structure is also constant
        if avg_jaccard_sim >= stability_jaccard_threshold:
            return "Stable"
        else:
            return "Volatile (size is stable, but components are changing)"


