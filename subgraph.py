class TrendAnalysisStrategy:
    """Base class for a trend analysis strategy."""
    def __init__(self, name: str):
        self.name = name

    def analyze(self, graphs: List[nx.Graph]) -> str:
        raise NotImplementedError

    def _load_graphs(self, folder_path: str) -> Dict[str, List[nx.Graph]]:
        activities = {}
        if not os.path.isdir(folder_path): return {}
        for filename in sorted(os.listdir(folder_path)):
            if not filename.endswith(".ttl"): continue
            match = re.match(r"(\d{4}-\d{2}-\d{2})_(anchor_\d+)\.ttl", filename)
            if not match: continue
            _, anchor_id = match.groups()
            rdf_graph = Graph().parse(os.path.join(folder_path, filename), format="turtle")
            nx_graph = nx.Graph()
            for s, p, o in rdf_graph:
                if not isinstance(o, Literal): nx_graph.add_edge(s, o)
            if anchor_id not in activities: activities[anchor_id] = []
            activities[anchor_id].append(nx_graph)
        return activities

# --- APPROACH 1: Jaccard + Size Analysis (Baseline) ---
class StrategyJaccardSize(TrendAnalysisStrategy):
    def __init__(self):
        super().__init__("Jaccard + Size")

    def analyze(self, graphs: List[nx.Graph]) -> str:
        if len(graphs) < 2: return "Insufficient Data"
        size_changes, jaccard_sims = [], []
        for g1, g2 in zip(graphs, graphs[1:]):
            s1, s2 = g1.number_of_nodes(), g2.number_of_nodes()
            if s1 > 0: size_changes.append((s2 - s1) / s1)
            n1, n2 = set(g1.nodes()), set(g2.nodes())
            union = len(n1.union(n2))
            jaccard_sims.append(len(n1.intersection(n2)) / union if union > 0 else 0)

        if not size_changes: return "Insufficient Data"
        avg_size_change, avg_jaccard = np.mean(size_changes), np.mean(jaccard_sims)

        if avg_size_change > 0.15: return "Growing"
        if avg_size_change < -0.15: return "Decaying"
        if avg_jaccard > 0.7: return "Stable"
        if avg_jaccard < 0.2: return "Shifting"
        return "Volatile"

# --- APPROACH 2: Time Series on Graph Metrics ---
class StrategyTimeSeriesMetrics(TrendAnalysisStrategy):
    def __init__(self):
        super().__init__("Time Series on Graph Metrics")

    def analyze(self, graphs: List[nx.Graph]) -> str:
        if len(graphs) < 3: return "Insufficient Data"
        nodes = [g.number_of_nodes() for g in graphs]
        time_steps = list(range(len(graphs)))
        node_slope, _, r_val, _, _ = linregress(time_steps, nodes)
        mean_nodes = np.mean(nodes)
        norm_slope = node_slope / mean_nodes if mean_nodes > 0 else 0

        if r_val**2 > 0.6: # Strong linear trend
            if norm_slope > 0.05: return "Growing"
            if norm_slope < -0.05: return "Decaying"

        node_variance = np.std(nodes) / mean_nodes if mean_nodes > 0 else 0
        if node_variance < 0.1: return "Stable"
        if node_variance > 0.4: return "Volatile"
        return "Shifting"

