def group_subgraphs_by_activity(folder_path: str) -> Dict[str, List[Tuple[datetime, nx.Graph]]]:
    """
    Scans a directory for .ttl files and groups them by anchor, converting them to NetworkX graphs.
    """
    activities = {}
    for filename in sorted(os.listdir(folder_path)):
        if not filename.endswith(".ttl"):
            continue

        match = re.match(r"(\d{4}-\d{2}-\d{2})_(anchor_\d+)\.ttl", filename)
        if not match:
            continue

        date_str, anchor_id = match.groups()
        try:
            timestamp = datetime.strptime(date_str, "%Y-%m-%d")
            rdf_graph = Graph().parse(os.path.join(folder_path, filename), format="turtle")

            # Convert rdflib.Graph to networkx.Graph for analysis
            nx_graph = nx.Graph()
            for s, p, o in rdf_graph:
                if isinstance(o, Literal): continue # Literals are not nodes in the graph structure
                nx_graph.add_edge(s, o)

            if anchor_id not in activities:
                activities[anchor_id] = []
            activities[anchor_id].append((timestamp, nx_graph))

        except Exception as e:
            print(f"Warning: Could not process file '{filename}'. Reason: {e}")
            continue

    return activities

def calculate_graph_similarity(g1: nx.Graph, g2: nx.Graph) -> Tuple[float, float]:
    """Calculates the Jaccard similarity for nodes and edges between two graphs."""
    nodes1, nodes2 = set(g1.nodes()), set(g2.nodes())
    edges1 = set(tuple(sorted(e)) for e in g1.edges())
    edges2 = set(tuple(sorted(e)) for e in g2.edges())

    node_union = len(nodes1.union(nodes2))
    node_jaccard = len(nodes1.intersection(nodes2)) / node_union if node_union > 0 else 0

    edge_union = len(edges1.union(edges2))
    edge_jaccard = len(edges1.intersection(edges2)) / edge_union if edge_union > 0 else 0

    return node_jaccard, edge_jaccard

def analyze_activity_trend(graphs: List[nx.Graph], **kwargs) -> str:
    """Analyzes a sequence of graphs to determine its trend."""
    # Tunable parameters
    growth_threshold = kwargs.get('growth_threshold', 0.15)
    decay_threshold = kwargs.get('decay_threshold', -0.15)
    stability_jaccard_threshold = kwargs.get('stability_jaccard_threshold', 0.7)

    if len(graphs) < 2:
        return "Insufficient Data"

    size_changes, jaccard_similarities = [], []
    for i in range(len(graphs) - 1):
        g1, g2 = graphs[i], graphs[i+1]
        size1, size2 = g1.number_of_nodes(), g2.number_of_nodes()
        if size1 > 0:
            size_changes.append((size2 - size1) / size1)
        node_jaccard, _ = calculate_graph_similarity(g1, g2)
        jaccard_similarities.append(node_jaccard)

    if not size_changes: return "Insufficient Data"

    avg_size_change = np.mean(size_changes)
    avg_jaccard_sim = np.mean(jaccard_similarities)

    print(f"    Metrics: Avg. Size Change: {avg_size_change:.2%}, Avg. Jaccard Sim: {avg_jaccard_sim:.2f}")

    if avg_size_change > growth_threshold: return "Growing"
    if avg_size_change < decay_threshold: return "Decaying"
    if avg_jaccard_sim >= stability_jaccard_threshold: return "Stable"
    return "Volatile"

