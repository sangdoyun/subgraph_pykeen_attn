# --- 2.2. Base Strategy Class ---
class TrendAnalysisStrategy:
    def __init__(self, name: str): self.name = name
    def analyze(self, graphs: List[nx.Graph]) -> str: raise NotImplementedError
    def _load_graphs(self, folder_path: str) -> Dict[str, List[nx.Graph]]:
        activities = {}
        if not os.path.isdir(folder_path): return {}
        for filename in sorted(os.listdir(folder_path)):
            if not filename.endswith(".ttl"): continue
            match = re.match(r"(\d{4}-\d{2}-\d{2})_(anchor_\d+)\.ttl", filename)
            if not match: continue
            _, anchor_id = match.groups()
            rdf_graph = Graph().parse(os.path.join(folder_path, filename), format="turtle")
            nx_graph = nx.Graph()
            for s, p, o in rdf_graph:
                if not isinstance(o, Literal): nx_graph.add_edge(s, o)
            if anchor_id not in activities: activities[anchor_id] = []
            activities[anchor_id].append(nx_graph)
        return activities

# --- 2.3. Analysis Strategies ---
class StrategyJaccardSize(TrendAnalysisStrategy):
    def __init__(self): super().__init__("Jaccard + Size")
    def analyze(self, graphs: List[nx.Graph]) -> str:
        if len(graphs) < 2: return "Insufficient Data"
        size_changes, jaccard_sims = [], []
        for g1, g2 in zip(graphs, graphs[1:]):
            s1, s2 = g1.number_of_nodes(), g2.number_of_nodes()
            if s1 > 0: size_changes.append((s2 - s1) / s1)
            n1, n2 = set(g1.nodes()), set(g2.nodes())
            union = len(n1.union(n2))
            jaccard_sims.append(len(n1.intersection(n2)) / union if union > 0 else 0)
        if not size_changes: return "Insufficient Data"
        avg_size_change, avg_jaccard = np.mean(size_changes), np.mean(jaccard_sims)
        if avg_size_change > 0.15: return "Growing"
        if avg_size_change < -0.15: return "Decaying"
        if avg_jaccard > 0.7: return "Stable"
        if avg_jaccard < 0.2: return "Shifting"
        return "Volatile"

class StrategyTimeSeriesMetrics(TrendAnalysisStrategy):
    def __init__(self): super().__init__("Time Series on Graph Metrics")
    def analyze(self, graphs: List[nx.Graph]) -> str:
        if len(graphs) < 3: return "Insufficient Data"
        nodes = [g.number_of_nodes() for g in graphs]
        slope, _, r_val, _, _ = linregress(list(range(len(graphs))), nodes)
        mean_nodes = np.mean(nodes)
        norm_slope = slope / mean_nodes if mean_nodes > 0 else 0
        if r_val**2 > 0.6:
            if norm_slope > 0.05: return "Growing"
            if norm_slope < -0.05: return "Decaying"
        node_variance = np.std(nodes) / mean_nodes if mean_nodes > 0 else 0
        if node_variance < 0.1: return "Stable"
        if node_variance > 0.4: return "Volatile"
        return "Shifting"

class StrategyNode2Vec(TrendAnalysisStrategy):
    def __init__(self, dimensions=16):
        super().__init__("Node2Vec Embedding")
        self.dimensions = dimensions
    def _get_graph_embedding(self, graph: nx.Graph) -> np.ndarray:
        if graph.number_of_nodes() == 0: return np.zeros(self.dimensions)
        n2v = Node2Vec(graph, dimensions=self.dimensions, walk_length=10, num_walks=50, workers=4, quiet=True)
        model = n2v.fit(window=5, min_count=1)
        node_vectors = [model.wv[str(node)] for node in graph.nodes()]
        return np.mean(node_vectors, axis=0) if node_vectors else np.zeros(self.dimensions)
    def analyze(self, graphs: List[nx.Graph]) -> str:
        if len(graphs) < 2: return "Insufficient Data"
        embeddings = [self._get_graph_embedding(g) for g in graphs]
        distances = [np.linalg.norm(e1 - e2) for e1, e2 in zip(embeddings, embeddings[1:])]
        avg_dist = np.mean(distances)
        if avg_dist < 0.1: return "Stable"
        if avg_dist > 0.5: return "Shifting"
        nodes = [g.number_of_nodes() for g in graphs]
        slope, _, _, _, _ = linregress(list(range(len(graphs))), nodes)
        norm_slope = slope / np.mean(nodes) if np.mean(nodes) > 0 else 0
        if norm_slope > 0.05: return "Growing"
        if norm_slope < -0.05: return "Decaying"
        return "Volatile"

class StrategyAdvancedEmbedding(TrendAnalysisStrategy):
    def __init__(self, generator: EmbeddingGenerator):
        super().__init__("Advanced Pre-Trained Embedding")
        self.generator = generator
    def _convert_nx_to_hetero(self, g: nx.Graph) -> HeteroData:
        data = HeteroData()
        node_map = {}
        # Heuristically map nx nodes to types and create features
        for node_type in NODE_TYPES:
            node_list = [n for n in g.nodes() if node_type in str(n).lower()]
            if node_list:
                data[node_type].x = torch.randn(len(node_list), NODE_FEATURE_DIM)
                node_map.update({node: i for i, node in enumerate(node_list)})

        # Map edges
        for src, dst in g.edges():
            src_type, dst_type = None, None
            for nt in NODE_TYPES:
                if nt in str(src).lower(): src_type = nt
                if nt in str(dst).lower(): dst_type = nt

            if src_type and dst_type:
                # Find a matching edge type from metadata
                for s, _, d in EDGE_TYPES:
                    if (s == src_type and d == dst_type) or (s == dst_type and d == src_type):
                        edge_type = (src_type, f'related_to_{dst_type}', dst_type)
                        if edge_type not in data.edge_types:
                             data[edge_type].edge_index = torch.empty((2,0), dtype=torch.long)

                        src_idx, dst_idx = node_map.get(src), node_map.get(dst)
                        if src_idx is not None and dst_idx is not None:
                            edge = torch.tensor([[src_idx], [dst_idx]], dtype=torch.long)
                            data[edge_type].edge_index = torch.cat([data[edge_type].edge_index, edge], dim=1)
        return data
    def analyze(self, graphs: List[nx.Graph]) -> str:
        if len(graphs) < 2: return "Insufficient Data"
        embeddings = []
        for g in graphs:
            if g.number_of_nodes() == 0: continue
            hetero_g = self._convert_nx_to_hetero(g)
            # Generate dummy timestamps as the model requires them
            timestamps = list(range(g.number_of_nodes()))
            emb = self.generator.get_embeddings(timestamps, hetero_g)['graph_embedding']
            embeddings.append(emb)

        if len(embeddings) < 2: return "Insufficient Data"
        distances = [np.linalg.norm(e1 - e2) for e1, e2 in zip(embeddings, embeddings[1:])]
        avg_dist = np.mean(distances)
        if avg_dist < 0.01: return "Stable" # Pre-trained models might produce very stable vecs
        if avg_dist > 0.1: return "Shifting"
        nodes = [g.number_of_nodes() for g in graphs]
        slope, _, _, _, _ = linregress(list(range(len(graphs))), nodes)
        norm_slope = slope / np.mean(nodes) if np.mean(nodes) > 0 else 0
        if norm_slope > 0.05: return "Growing"
        if norm_slope < -0.05: return "Decaying"
        return "Volatile"

# --- 2.4. Performance Evaluation ---
def evaluate_performance(strategy_name: str, y_true: List[str], y_pred: List[str], labels: List[str]):
    print(f"\n--- Performance Evaluation for: {strategy_name} ---")
    present_labels = sorted(list(set(y_true) | set(y_pred)))
    print(classification_report(y_true, y_pred, labels=present_labels, zero_division=0))
    cm = confusion_matrix(y_true, y_pred, labels=present_labels)
    disp = ConfusionMatrixDisplay(confusion_matrix=cm, display_labels=present_labels)
    fig, ax = plt.subplots(figsize=(8, 6))
    disp.plot(cmap=plt.cm.Blues, ax=ax, xticks_rotation='vertical')
    plt.title(f"Confusion Matrix for {strategy_name}")
    plt.tight_layout()
    plt.show()

