class StrategyNode2Vec(TrendAnalysisStrategy):
    def __init__(self, dimensions=16, walk_length=10, num_walks=50):
        super().__init__("Node2Vec Embedding")
        self.dimensions = dimensions
        self.walk_length = walk_length
        self.num_walks = num_walks

    def _get_graph_embedding(self, graph: nx.Graph) -> np.ndarray:
        if graph.number_of_nodes() == 0:
            return np.zeros(self.dimensions)

        # Node2Vec conversion
        n2v = Node2Vec(graph, dimensions=self.dimensions, walk_length=self.walk_length,
                       num_walks=self.num_walks, workers=4, quiet=True)
        model = n2v.fit(window=5, min_count=1, batch_words=4)

        # Aggregate node vectors (mean) to get a graph vector
        node_vectors = [model.wv[str(node)] for node in graph.nodes()]
        if not node_vectors:
            return np.zeros(self.dimensions)
        return np.mean(node_vectors, axis=0)

    def analyze(self, graphs: List[nx.Graph]) -> str:
        if len(graphs) < 2: return "Insufficient Data"

        embeddings = [self._get_graph_embedding(g) for g in graphs]

        # Same trajectory analysis as Approach 3, but on more powerful embeddings
        distances = [np.linalg.norm(e1 - e2) for e1, e2 in zip(embeddings, embeddings[1:])]
        avg_dist = np.mean(distances)

        if avg_dist < 0.1: return "Stable"
        if avg_dist > 0.5: return "Shifting"

        nodes = [g.number_of_nodes() for g in graphs]
        slope, _, _, _, _ = linregress(list(range(len(graphs))), nodes)
        norm_slope = slope / np.mean(nodes) if np.mean(nodes) > 0 else 0
        if norm_slope > 0.05: return "Growing"
        if norm_slope < -0.05: return "Decaying"
        return "Volatile"

