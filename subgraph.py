def extract_snapshot(g: Graph, day: date) -> Graph:
    """
    Extracts a snapshot of the TKG for a given day.
    NOTE: The provided TTL file has no timestamps. For this reason, we are treating
    the entire graph as a single snapshot for any given day in the range.
    This function can be modified to filter triples based on a timestamp predicate
    if your data includes it.
    """
    return g

def compute_node_embeddings(graph: nx.Graph, rdf_graph: Graph) -> Dict[URIRef, np.ndarray]:
    """
    Computes node embeddings based on node types and their immediate neighborhood.

    Args:
        graph (nx.Graph): The NetworkX graph representation.
        rdf_graph (Graph): The original rdflib graph to get type information.

    Returns:
        A dictionary mapping each node to its embedding vector.
    """
    print("  Computing node embeddings...")
    # Get all unique rdf:type values in the graph
    types = sorted(list(set(o for s, p, o in rdf_graph if p == RDF.type)))
    type_to_index = {t: i for i, t in enumerate(types)}
    embedding_dim = len(types)

    initial_embeddings = {}

    # Create initial one-hot encoded vectors for each node based on its type
    for node in graph.nodes():
        node_vector = np.zeros(embedding_dim)
        # Query rdflib graph for the type of the node
        node_types = list(rdf_graph.objects(subject=node, predicate=RDF.type))
        for t in node_types:
            if t in type_to_index:
                node_vector[type_to_index[t]] = 1
        initial_embeddings[node] = node_vector

    final_embeddings = {}
    # Aggregate embeddings from neighbors (1-hop message passing)
    for node in graph.nodes():
        neighbor_embeddings = [initial_embeddings[node]] # Include self
        for neighbor in graph.neighbors(node):
            if neighbor in initial_embeddings:
                neighbor_embeddings.append(initial_embeddings[neighbor])

        if neighbor_embeddings:
            final_embeddings[node] = np.mean(neighbor_embeddings, axis=0)
        else:
            final_embeddings[node] = initial_embeddings[node]

    print(f"  Embeddings computed for {len(final_embeddings)} nodes.")
    return final_embeddings

def cosine_similarity(vec1: np.ndarray, vec2: np.ndarray) -> float:
    """Calculates the cosine similarity between two vectors."""
    dot_product = np.dot(vec1, vec2)
    norm_vec1 = np.linalg.norm(vec1)
    norm_vec2 = np.linalg.norm(vec2)
    if norm_vec1 == 0 or norm_vec2 == 0:
        return 0.0
    return dot_product / (norm_vec1 * norm_vec2)

def extract_subgraph_with_embedding_filter(
    graph: nx.Graph,
    anchor_node: URIRef,
    embeddings: Dict[URIRef, np.ndarray],
    radius: int = 3,
    threshold: float = 0.5
) -> nx.Graph:
    """
    Extracts a subgraph by expanding from an anchor and filtering edges by embedding similarity.
    """
    if anchor_node not in graph:
        print(f"    Anchor node {anchor_node} not in graph.")
        return nx.Graph()

    # 1. Expand from the anchor to get a k-hop neighborhood
    ego_graph = nx.ego_graph(graph, anchor_node, radius=radius)

    # 2. Filter edges in the ego-graph based on embedding similarity
    filtered_subgraph = nx.Graph()
    for u, v in ego_graph.edges():
        if u in embeddings and v in embeddings:
            sim = cosine_similarity(embeddings[u], embeddings[v])
            if sim >= threshold:
                filtered_subgraph.add_edge(u, v, **graph.get_edge_data(u, v))

    # Ensure all nodes from kept edges are in the graph, even if they become isolates
    if filtered_subgraph.number_of_edges() > 0:
        for node in ego_graph.nodes():
             if node not in filtered_subgraph:
                 # Check if any neighbor connection was kept
                 if any(neighbor in filtered_subgraph for neighbor in graph.neighbors(node)):
                    filtered_subgraph.add_node(node)

    return filtered_subgraph


def process_tkg_for_user(
    tkg_file_path: str,
    user_id: int,
    start_date: date,
    end_date: date,
    daily_anchor_nodes: Dict[date, List[URIRef]],
    subgraph_radius: int = 3,
    similarity_threshold: float = 0.1
):
    """
    Processes a TKG for a specific user over a date range.
    """
    output_dir = f"user{user_id}_subgraphs"
    os.makedirs(output_dir, exist_ok=True)
    print(f"\n--- Processing User ID: {user_id} from {tkg_file_path} ---")
    print(f"Output directory: {output_dir}")

    # Load the main TKG
    tkg = Graph()
    tkg.parse(tkg_file_path, format="turtle")

    current_date = start_date
    while current_date <= end_date:
        print(f"Processing snapshot for {current_date}...")

        daily_snapshot_rdf = extract_snapshot(tkg, current_date)

        if not daily_snapshot_rdf:
            print(f"  No data in snapshot for {current_date}.")
            current_date += timedelta(days=1)
            continue

        daily_graph_nx = nx.Graph()
        for s, p, o in daily_snapshot_rdf:
            if isinstance(o, Literal): # Don't add literals as nodes
                continue
            daily_graph_nx.add_edge(s, o, label=p)

        # Compute embeddings for the entire daily graph
        embeddings = compute_node_embeddings(daily_graph_nx, daily_snapshot_rdf)

        anchors = daily_anchor_nodes.get(current_date, [])
        if not anchors:
            print(f"  No anchor nodes for {current_date}.")
            current_date += timedelta(days=1)
            continue

        for i, anchor in enumerate(anchors):
            print(f"  Extracting subgraph around anchor: {anchor}")
            activity_subgraph = extract_subgraph_with_embedding_filter(
                daily_graph_nx,
                anchor,
                embeddings,
                radius=subgraph_radius,
                threshold=similarity_threshold
            )

            if activity_subgraph.number_of_nodes() > 0:
                subgraph_filename = f"{current_date}_anchor_{i+1}.gml"
                subgraph_path = os.path.join(output_dir, subgraph_filename)
                nx.write_gml(activity_subgraph, subgraph_path)
                print(f"    Saved subgraph with {activity_subgraph.number_of_nodes()} nodes and {activity_subgraph.number_of_edges()} edges to {subgraph_path}")
            else:
                print(f"    No subgraph extracted for anchor {anchor} with the given parameters.")

        current_date += timedelta(days=1)

