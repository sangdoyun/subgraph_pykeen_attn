import matplotlib.pyplot as plt
import matplotlib.dates as mdates
from collections import defaultdict

# 1. Group events by type
def group_events_by_type(events):
    grouped = defaultdict(list)
    for event in events:
        start = datetime.fromisoformat(event["start_time"])
        end = datetime.fromisoformat(event["end_time"])
        grouped[event["type"]].append((start, end))
    return grouped

# 2. Plot function
def plot_life_events(events):
    grouped = group_events_by_type(events)
    fig, ax = plt.subplots(figsize=(12, 6))

    event_types = list(grouped.keys())
    colors = plt.cm.tab10.colors

    for i, event_type in enumerate(event_types):
        for (start, end) in grouped[event_type]:
            ax.plot([start, end], [i, i], color=colors[i % len(colors)], linewidth=3)

    # Format y-axis
    ax.set_yticks(range(len(event_types)))
    ax.set_yticklabels(event_types)
    ax.set_xlabel("Date")
    ax.set_title("User Life Events Timeline (Simulated)")

    # Format x-axis
    ax.xaxis.set_major_locator(mdates.DayLocator(interval=5))
    ax.xaxis.set_major_formatter(mdates.DateFormatter('%b %d'))
    fig.autofmt_xdate()

    plt.tight_layout()
    plt.grid(True, axis='x', linestyle='--', alpha=0.3)
    plt.show()

# 3. Call the function
plot_life_events(events)

