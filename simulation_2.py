fake = Faker()

# ---- Constants ----
MODALITIES = ['gps', 'accelerometer', 'apps', 'camera', 'mic', 'screen', 'bluetooth']
LOCATIONS = ['New York, USA', 'London, UK', 'Tokyo, Japan', 'Delhi, India', 'Paris, France']
SCENES = ['kitchen', 'classroom', 'gym', 'office', 'street', 'cafe', 'living room']
FACES = ['family', 'friend', 'colleague']

# ---- Simulation Functions ----

def simulate_time_series(days, trend='stable', base_rate=3):
    timestamps = []
    for day in range(days):
        if trend == 'growing':
            rate = base_rate + 0.1 * day
        elif trend == 'decaying':
            rate = max(base_rate - 0.05 * day, 0.5)
        else:  # stable
            rate = base_rate
        count = np.random.poisson(rate)
        for _ in range(count):
            hour = random.randint(6, 23)
            timestamps.append((day, hour))
    return timestamps

def simulate_gps_location():
    lat = round(random.uniform(-90, 90), 6)
    lon = round(random.uniform(-180, 180), 6)
    city_info = random.choice(LOCATIONS).split(", ")
    return {
        'lat': lat,
        'lon': lon,
        'city': city_info[0],
        'state': 'N/A',
        'country': city_info[1]
    }

def simulate_faces():
    faces = []
    num_faces = random.randint(0, 3)
    for i in range(num_faces):
        faces.append({
            'id': f'face_{i}',
            'gender': random.choice(['M', 'F']),
            'age': random.randint(5, 70),
            'bbox': [random.randint(0, 100), random.randint(0, 100), 50, 50],
            'relation': random.choice(FACES)
        })
    return faces

def simulate_camera_event():
    return {
        'location': simulate_gps_location(),
        'faces': simulate_faces(),
        'scene': random.choice(SCENES)
    }

def simulate_daily_modality(user, day, trend_map):
    day_data = {'user_id': user['user_id'], 'day': day}

    for modality in MODALITIES:
        trend = trend_map.get(modality, 'stable')
        timestamps = simulate_time_series(1, trend)
        if modality == 'gps':
            day_data['gps'] = [simulate_gps_location() for _ in timestamps]
        elif modality == 'accelerometer':
            day_data['accelerometer'] = [{'x': round(random.gauss(0, 1), 2),
                                          'y': round(random.gauss(0, 1), 2),
                                          'z': round(random.gauss(9.8, 1), 2)} for _ in timestamps]
        elif modality == 'apps':
            day_data['apps'] = random.sample(user['favorite_apps'], k=random.randint(1, len(user['favorite_apps'])))
        elif modality == 'camera':
            day_data['camera'] = [simulate_camera_event() for _ in timestamps]
        elif modality == 'mic':
            day_data['mic'] = [{'duration_sec': random.randint(2, 300)} for _ in timestamps]
        elif modality == 'screen':
            day_data['screen'] = [{'screen_on': random.randint(5, 30)} for _ in timestamps]
        elif modality == 'bluetooth':
            day_data['bluetooth'] = [{'device': fake.word(), 'strength': round(random.uniform(-90, -30), 1)} for _ in timestamps]

        # Ground truth pattern label
        day_data[f'{modality}_pattern'] = trend

    return day_data

# ---- Generate full timeline data for multiple users ----

def simulate_smartphone_timeline(users, days=7):
    timeline_data = []
    for user in users:
        trend_map = {
            'gps': random.choice(['growing', 'decaying', 'stable']),
            'accelerometer': random.choice(['growing', 'decaying', 'stable']),
            'apps': random.choice(['growing', 'decaying', 'stable']),
            'camera': random.choice(['growing', 'decaying', 'stable']),
            'mic': random.choice(['growing', 'decaying', 'stable']),
            'screen': random.choice(['growing', 'decaying', 'stable']),
            'bluetooth': random.choice(['growing', 'decaying', 'stable']),
        }
        for day in range(days):
            day_record = simulate_daily_modality(user, day, trend_map)
            timeline_data.append(day_record)
    return timeline_data

