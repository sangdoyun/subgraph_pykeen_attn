# -------- Utility --------
def create_event(event_type, day, start_hour, duration_hours=1):
    start_time = day + timedelta(hours=start_hour)
    end_time = start_time + timedelta(hours=duration_hours)
    return {
        "type": event_type,
        "start_time": start_time,
        "end_time": end_time
    }

# -------- Simulators --------
def simulate_events_by_trend(event_type, trend, start_date, days=60):
    events = []
    current = 0
    for day in range(days):
        base_day = start_date + timedelta(days=day)
        if trend == 'growing':
            prob = min(0.1 + 0.01 * day, 0.9)
        elif trend == 'decaying':
            prob = max(0.9 - 0.01 * day, 0.05)
        else:  # stable
            prob = 0.3
        if random.random() < prob:
            events.append(create_event(event_type, base_day, random.randint(7, 22), random.choice([1, 2])))
    return events

def simulate_routine(personality, start_date, days=60):
    events = []
    for day in range(days):
        date = start_date + timedelta(days=day)
        if personality == 'morning_person':
            events.append(create_event("routine", date, random.randint(6, 9)))
        elif personality == 'night_owl':
            events.append(create_event("routine", date, random.randint(20, 23)))
        else:
            events.append(create_event("routine", date, random.randint(10, 22)))
    return events

def simulate_communication(start_date, days=60, mu=0.2, alpha=0.8, beta=1.2):
    t = 0
    events = []
    timestamps = []
    while t < days:
        lambda_t = mu + sum([alpha * np.exp(-beta * (t - e)) for e in timestamps])
        w = -np.log(np.random.rand()) / lambda_t
        t += w
        if t >= days:
            break
        e_day = start_date + timedelta(days=int(t))
        events.append(create_event("communication", e_day, random.randint(9, 22)))
        timestamps.append(t)
    return events

# -------- Master Timeline Generator --------
def simulate_user_life(user, start_date, days=60):
    all_events = []
    for interest, trend in user['interest_pref'].items():
        all_events += simulate_events_by_trend(interest, trend, start_date, days)
    all_events += simulate_routine(user['personality'], start_date, days)
    all_events += simulate_communication(start_date, days)
    return sorted(all_events, key=lambda x: x['start_time'])

# -------- Plotter --------
def plot_user_timeline(events, user_id):
    grouped = defaultdict(list)
    for e in events:
        grouped[e['type']].append((e['start_time'], e['end_time']))

    fig, ax = plt.subplots(figsize=(12, 6))
    event_types = list(grouped.keys())
    for i, etype in enumerate(event_types):
        for (start, end) in grouped[etype]:
            ax.plot([start, end], [i, i], lw=4, label=etype if i == 0 else "", alpha=0.7)

    ax.set_yticks(range(len(event_types)))
    ax.set_yticklabels(event_types)
    ax.set_title(f"Timeline of Life Events for {user_id}")
    ax.set_xlabel("Date")
    ax.grid(True, axis='x', linestyle='--', alpha=0.3)
    plt.tight_layout()
    plt.show()

