# Load the simulated data
try:
    with open("simulated_smartphone_data.json", 'r') as f:
        all_users_data = json.load(f)
except FileNotFoundError:
    print("Error: simulated_smartphone_data.json not found. Please run the simulation code first.")
    exit()

# --- Data Processing for Visualization ---

def parse_iso_date(iso_str):
    """Parses an ISO format string to a datetime object."""
    return datetime.fromisoformat(iso_str)

def get_phase_info(event_type, event_gt, current_timestamp):
    """Determines which phase an event falls into."""
    for phase_name, phase_dates in event_gt['phases'].items():
        start_date = parse_iso_date(phase_dates['start_date'])
        end_date = parse_iso_date(phase_dates['end_date'])
        if start_date <= current_timestamp < end_date:
            return phase_name
    return "baseline" # If not in any specific phase, it's baseline

def analyze_activity_by_phase(user_data):
    """Analyzes activity counts for each modality across different phases."""
    activity_counts = []

    # Get all events and their timestamps, and add modality type
    all_events = []
    for modality, events in user_data['all_simulated_data'].items():
        for event in events:
            timestamp_str = event.get('timestamp') or event.get('date') or event.get('start_date')
            if timestamp_str:
                all_events.append({
                    'modality': modality,
                    'timestamp': parse_iso_date(timestamp_str)
                })

    for event_data in all_events:
        timestamp = event_data['timestamp']
        modality = event_data['modality']

        # Check against travel events
        current_travel_phase = "baseline"
        for travel_event_gt in user_data['travel_events']:
            phase = get_phase_info('travel', travel_event_gt, timestamp)
            if phase != "baseline":
                current_travel_phase = phase
                break # Assume one active travel event at a time

        # Check against interest changes
        current_interest_phase = "baseline"
        for interest_event_gt in user_data['interest_changes']:
            phase = get_phase_info('interest', interest_event_gt, timestamp)
            if phase != "baseline":
                current_interest_phase = phase
                break # Assume one active interest event at a time

        # Determine the overall "active" phase for the event
        # Prioritize travel over interest, then interest over baseline
        active_phase = "baseline"
        if current_travel_phase != "baseline":
            # Append destination city to travel phase for clarity in plot
            travel_destination_city = next((t['destination_city'] for t in user_data['travel_events'] if get_phase_info('travel', t, timestamp) == current_travel_phase), "")
            active_phase = f"Travel ({current_travel_phase}) - {travel_destination_city}"
        elif current_interest_phase != "baseline":
            # Append interest type to interest phase for clarity in plot
            interest_type = next((i['interest_type'] for i in user_data['interest_changes'] if get_phase_info('interest', i, timestamp) == current_interest_phase), "")
            active_phase = f"Interest ({current_interest_phase}) - {interest_type.capitalize()}"

        activity_counts.append({
            'modality': modality,
            'phase': active_phase,
            'user_id': user_data['user_id']
        })

    return pd.DataFrame(activity_counts)

# --- Generate Plots ---

all_activity_dfs = []
for user_data in all_users_data:
    all_activity_dfs.append(analyze_activity_by_phase(user_data))

combined_df = pd.concat(all_activity_dfs)

