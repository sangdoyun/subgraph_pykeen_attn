def simulate_user_data(user_id):
    user_data = {
        "user_id": user_id,
        "travel_events": [],
        "interest_changes": [],
        "all_simulated_data": {
            "app_usage": [],
            "call_log": [],
            "calendar_events": [],
            "contacts": [],
            "gallery_images": []
        }
    }

    # Initialize user-specific data pools
    user_contacts = {} # Stores contact_id -> contact_info
    user_persons = {} # Stores person_id -> person_info
    user_home_location = random.choice(HOME_LOCATIONS)
    user_time_zone = random.choice(TIME_ZONES)

    # Schedule Travel Events (2 per user)
    travel_schedules = []
    for i in range(2):
        # Ensure travel periods don't overlap significantly
        while True:
            travel_start_day_idx = random.randint(30, SIM_DAYS - (TRAVEL_TRIGGER_DURATION + TRAVEL_GROWING_DURATION + TRAVEL_DECAY_DURATION) - 30)
            travel_end_day_idx = travel_start_day_idx + TRAVEL_TRIGGER_DURATION + TRAVEL_GROWING_DURATION + TRAVEL_DECAY_DURATION

            overlap = False
            # Iterate over existing schedules, unpacking 3 values for existing_start, existing_end, and the ignored third element
            for existing_start, existing_end, _ in travel_schedules:
                if not (travel_end_day_idx < existing_start or travel_start_day_idx > existing_end):
                    overlap = True
                    break
            if not overlap:
                travel_destination = random.choice(TRAVEL_DESTINATIONS) # Choose destination here
                travel_schedules.append((travel_start_day_idx, travel_end_day_idx, travel_destination)) # Append the 3-element tuple
                break

    # Schedule Interest Change Event (1 per user)
    interest_schedules = []
    while True:
        interest_start_day_idx = random.randint(30, SIM_DAYS - (INTEREST_TRIGGER_DURATION + INTEREST_GROWING_DURATION + INTEREST_STABLE_DURATION) - 30)
        interest_end_day_idx = interest_start_day_idx + INTEREST_TRIGGER_DURATION + INTEREST_GROWING_DURATION + INTEREST_STABLE_DURATION

        overlap = False
        for existing_start, existing_end, _ in travel_schedules: # Check against travel schedules (which now correctly store 3 elements)
            if not (interest_end_day_idx < existing_start or interest_start_day_idx > existing_end):
                overlap = True
                break
        if not overlap:
            interest_type = random.choice(['finance', 'fitness', 'language'])
            interest_schedules.append((interest_start_day_idx, interest_end_day_idx, interest_type))
            break

    # Sort schedules to process chronologically
    all_events_schedule = []
    for idx, (start, end, dest) in enumerate(travel_schedules):
        all_events_schedule.append({
            "type": "travel",
            "id": f"travel_{idx+1}",
            "start_day": start,
            "end_day": end,
            "destination": dest
        })
    for idx, (start, end, int_type) in enumerate(interest_schedules):
        all_events_schedule.append({
            "type": "interest",
            "id": f"interest_{idx+1}",
            "start_day": start,
            "end_day": end,
            "interest_type": int_type
        })
    all_events_schedule.sort(key=lambda x: x["start_day"])


    # Main Simulation Loop
    for day_idx in range(SIM_DAYS):
        current_date = START_DATE + timedelta(days=day_idx)
        current_location_for_day = user_home_location # Default to home
        current_app_list = COMMON_APP_PACKAGES
        current_scene_list = HOME_SCENES

        active_event = None
        for event in all_events_schedule:
            if event["start_day"] <= day_idx < event["end_day"]:
                active_event = event
                break # Prioritize events if there's any overlap (though we tried to avoid)

        if active_event and active_event["type"] == "travel":
            travel_id = active_event["id"]
            travel_destination = active_event["destination"]

            # Determine travel phase and update GT
            if day_idx == active_event["start_day"]: # Trigger day
                phase_name = "trigger"
                user_data["travel_events"].append({
                    "travel_id": travel_id,
                    "destination_city": travel_destination["city"],
                    "phases": {
                        "trigger": {"start_date": current_date.isoformat(), "end_date": (current_date + timedelta(days=TRAVEL_TRIGGER_DURATION)).isoformat(), "trigger_event_type": "Calendar Event: Trip to " + travel_destination["city"]}
                    }
                })
                simulate_baseline_day(user_id, current_date, user_home_location, user_contacts, user_persons, user_time_zone, user_data["all_simulated_data"])
            elif active_event["start_day"] < day_idx < active_event["start_day"] + TRAVEL_TRIGGER_DURATION + TRAVEL_GROWING_DURATION: # Growing phase
                phase_name = "growing"
                current_location_for_day = travel_destination
                user_data["travel_events"][-1]["phases"]["growing"] = {"start_date": (START_DATE + timedelta(days=active_event["start_day"] + TRAVEL_TRIGGER_DURATION)).isoformat(), "end_date": (START_DATE + timedelta(days=active_event["start_day"] + TRAVEL_TRIGGER_DURATION + TRAVEL_GROWING_DURATION)).isoformat()}
                simulate_travel_day(user_id, current_date, travel_destination, user_contacts, user_persons, user_time_zone, user_data["all_simulated_data"])
            else: # Decay phase
                phase_name = "decay"
                user_data["travel_events"][-1]["phases"]["decay"] = {"start_date": (START_DATE + timedelta(days=active_event["start_day"] + TRAVEL_TRIGGER_DURATION + TRAVEL_GROWING_DURATION)).isoformat(), "end_date": (START_DATE + timedelta(days=active_event["end_day"])).isoformat()}
                simulate_baseline_day(user_id, current_date, user_home_location, user_contacts, user_persons, user_time_zone, user_data["all_simulated_data"]) # Back to home activity

            # Add a specific trigger event on the trigger day
            if day_idx == active_event["start_day"]:
                # Example: Add a specific calendar event for travel trigger
                trigger_ts = generate_timestamp(current_date, current_date + timedelta(days=1))
                user_data["all_simulated_data"]["calendar_events"].append({
                    "identifier": str(uuid.uuid4()),
                    "idnum": random.randint(10000, 99999),
                    "title": f"Trip to {travel_destination['city']} Planning",
                    "description": "Travel planning event (simulated trigger).",
                    "start_date": trigger_ts.isoformat(),
                    "end_date": (trigger_ts + timedelta(hours=1)).isoformat(),
                    "location": "Home",
                    "organizer": "user_self",
                    "attendees": [],
                    "reminders": []
                })
                # Or a specific image with new location tag:
                user_data["all_simulated_data"]["gallery_images"].append(generate_gallery_image(
                    trigger_ts, travel_destination, ['travel documents', 'map screenshot'], user_persons, user_time_zone
                ))

        elif active_event and active_event["type"] == "interest":
            interest_id = active_event["id"]
            interest_type = active_event["interest_type"]

            # Determine interest phase and update GT
            if day_idx == active_event["start_day"]: # Trigger day
                phase_name = "trigger"
                user_data["interest_changes"].append({
                    "interest_id": interest_id,
                    "interest_type": interest_type,
                    "phases": {
                        "trigger": {"start_date": current_date.isoformat(), "end_date": (current_date + timedelta(days=INTEREST_TRIGGER_DURATION)).isoformat(), "trigger_event_type": f"App Usage Surge: {interest_type.capitalize()} Apps"}
                    }
                })
                simulate_baseline_day(user_id, current_date, user_home_location, user_contacts, user_persons, user_time_zone, user_data["all_simulated_data"])
            elif active_event["start_day"] < day_idx < active_event["start_day"] + INTEREST_TRIGGER_DURATION + INTEREST_GROWING_DURATION: # Growing phase
                phase_name = "growing"
                user_data["interest_changes"][-1]["phases"]["growing"] = {"start_date": (START_DATE + timedelta(days=active_event["start_day"] + INTEREST_TRIGGER_DURATION)).isoformat(), "end_date": (START_DATE + timedelta(days=active_event["start_day"] + INTEREST_TRIGGER_DURATION + INTEREST_GROWING_DURATION)).isoformat()}
                simulate_interest_day(user_id, current_date, interest_type, user_home_location, user_contacts, user_persons, user_time_zone, user_data["all_simulated_data"])
            else: # Stable phase
                phase_name = "stable"
                user_data["interest_changes"][-1]["phases"]["stable"] = {"start_date": (START_DATE + timedelta(days=active_event["start_day"] + INTEREST_TRIGGER_DURATION + INTEREST_GROWING_DURATION)).isoformat(), "end_date": (START_DATE + timedelta(days=active_event["end_day"])).isoformat()}
                simulate_interest_day(user_id, current_date, interest_type, user_home_location, user_contacts, user_persons, user_time_zone, user_data["all_simulated_data"])

            # Add a specific trigger event on the trigger day
            if day_idx == active_event["start_day"]:
                # Example: Add a surge in specific app usage for interest trigger
                trigger_ts = generate_timestamp(current_date, current_date + timedelta(days=1))
                app_list_for_trigger = []
                if interest_type == 'finance': app_list_for_trigger = FINANCE_APP_PACKAGES
                elif interest_type == 'fitness': app_list_for_trigger = FITNESS_APP_PACKAGES
                elif interest_type == 'language': app_list_for_trigger = LANGUAGE_APP_PACKAGES

                for _ in range(5): # 5 extra app usage events
                    user_data["all_simulated_data"]["app_usage"].append(generate_app_usage(
                        trigger_ts, user_home_location, app_list_for_trigger, ['foreground'], user_time_zone
                    ))
                # Or a specific image with new scene tag:
                scene_for_trigger = []
                if interest_type == 'finance': scene_for_trigger = ['stock chart']
                elif interest_type == 'fitness': scene_for_trigger = ['gym interior']
                elif interest_type == 'language': scene_for_trigger = ['foreign city street sign']
                user_data["all_simulated_data"]["gallery_images"].append(generate_gallery_image(
                    trigger_ts, user_home_location, scene_for_trigger, user_persons, user_time_zone
                ))

        else: # Baseline activity
            simulate_baseline_day(user_id, current_date, user_home_location, user_contacts, user_persons, user_time_zone, user_data["all_simulated_data"])

    return user_data

