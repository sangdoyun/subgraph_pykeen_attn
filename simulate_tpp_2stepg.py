def generate_app_usage(timestamp, current_location_data, app_list, event_type_list, time_zone):
    return {
        "identifier": str(uuid.uuid4()),
        "timestamp": timestamp.isoformat(),
        "duration": random.randint(10, 3600), # seconds
        "package_name": random.choice(app_list),
        "event_type": random.choice(event_type_list),
        "time_zone": time_zone
    }

def generate_call_log(timestamp, current_location_data, user_contacts, time_zone):
    contact_id = get_random_contact_id(user_contacts)
    return {
        "identifier": str(uuid.uuid4()),
        "date": timestamp.isoformat(),
        "type": random.choice(['incoming', 'outgoing', 'missed']),
        "geocoded_loc": generate_location('home', current_location_data), # Calls often from home or current location
        "duration": random.randint(10, 1200), # seconds
        "number": user_contacts[contact_id]["phones"][0],
        "contact_id": contact_id,
        "call_rec": random.choice([True, False]),
        "call_rec_transcript": "Dummy transcript text.",
        "ai_summary": "Dummy AI summary.",
        "ai_keywords": random.sample(['meeting', 'family', 'work', 'friends', 'travel plans'], k=random.randint(1, 3)),
        "entities": random.sample(['person_name', 'organization', 'location'], k=random.randint(0, 2))
    }

def generate_calendar_event(timestamp, current_location_data, user_contacts, time_zone):
    start_date = timestamp
    end_date = start_date + timedelta(hours=random.randint(1, 4))
    attendees = [get_random_contact_id(user_contacts) for _ in range(random.randint(0, 2))]
    reminders = [start_date - timedelta(minutes=random.randint(10, 60))] if random.random() < 0.5 else []
    return {
        "identifier": str(uuid.uuid4()),
        "idnum": random.randint(10000, 99999),
        "title": random.choice(['Meeting', 'Appointment', 'Birthday', 'Travel Planning', 'Workout']),
        "description": "Dummy event description.",
        "start_date": start_date.isoformat(),
        "end_date": end_date.isoformat(),
        "location": random.choice([current_location_data["city"], "Online", "Client Office"]),
        "organizer": "user_self",
        "attendees": attendees,
        "reminders": [r.isoformat() for r in reminders]
    }

def generate_contact(timestamp, user_contacts, time_zone):
    contact_id = get_random_contact_id(user_contacts) # This will create a new one if not picked
    contact_info = user_contacts[contact_id]
    return {
        "identifier": str(uuid.uuid4()),
        "last_updated": timestamp.isoformat(),
        "display_name": contact_info["display_name"],
        "photo_uri": random.choice([True, False]),
        "contact_id": contact_id,
        "phones": contact_info["phones"],
        "normalized_num": [p.replace('+', '').replace(' ', '') for p in contact_info["phones"]],
        "names": [{"first": contact_info["display_name"].split()[0], "last": contact_info["display_name"].split()[-1]}],
        "emails": contact_info["emails"]
    }

