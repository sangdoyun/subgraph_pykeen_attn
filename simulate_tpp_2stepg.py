plot_data = plot_data.set_index(['user_id', 'phase', 'modality']).reindex(full_index, fill_value=0).reset_index()


# Order phases for better visualization
# This order needs to be dynamic based on the actual destinations/interests
# We'll create a custom sort key for phases
def custom_phase_sort_key(phase_name):
    if phase_name == "baseline":
        return 0
    elif "Travel" in phase_name:
        if "trigger" in phase_name: return 1
        if "growing" in phase_name: return 2
        if "decay" in phase_name: return 3
    elif "Interest" in phase_name:
        if "trigger" in phase_name: return 4
        if "growing" in phase_name: return 5
        if "stable" in phase_name: return 6
    return 99 # Fallback for unexpected phases

plot_data['phase_sort_order'] = plot_data['phase'].apply(custom_phase_sort_key)
plot_data = plot_data.sort_values(by=['user_id', 'phase_sort_order', 'phase', 'modality']).drop(columns='phase_sort_order')

# Now convert 'phase' to categorical with the determined order
plot_data['phase'] = pd.Categorical(plot_data['phase'], categories=plot_data['phase'].unique(), ordered=True)


