# --- Helper Functions ---

def generate_timestamp(start_dt, end_dt):
    """Generates a random datetime object within a given range."""
    time_diff = end_dt - start_dt
    random_seconds = random.uniform(0, time_diff.total_seconds())
    return start_dt + timedelta(seconds=random_seconds)

def generate_location(loc_type, city_data=None):
    """Generates a location dictionary based on type."""
    if loc_type == 'home':
        loc = random.choice(HOME_LOCATIONS)
    elif loc_type == 'travel' and city_data:
        loc = city_data
    else: # Default to home if something goes wrong
        loc = random.choice(HOME_LOCATIONS)

    return {
        "lat": loc["lat"] + random.uniform(-0.01, 0.01), # Add slight variation
        "lon": loc["lon"] + random.uniform(-0.01, 0.01),
        "city": loc["city"],
        "state": loc["state"],
        "country": loc["country"]
    }

def get_random_contact_id(user_contacts):
    """Returns an existing contact_id or generates a new one."""
    if random.random() < 0.8 and user_contacts: # 80% chance to pick existing
        return random.choice(list(user_contacts.keys()))
    else:
        new_contact_id = str(uuid.uuid4())
        user_contacts[new_contact_id] = {
            "display_name": random.choice(CONTACT_NAMES),
            "phones": [f"+1{random.randint(1000000000, 9999999999)}"],
            "emails": [f"{random.choice(CONTACT_NAMES).replace(' ', '.').lower()}@example.com"]
        }
        return new_contact_id

def get_random_person_id(user_persons):
    """Returns an existing person_id or generates a new one."""
    if random.random() < 0.7 and user_persons: # 70% chance to pick existing
        return random.choice(list(user_persons.keys()))
    else:
        new_person_id = str(uuid.uuid4())
        user_persons[new_person_id] = {
            "gender": random.choice(PERSON_GENDERS),
            "age": random.choice(PERSON_AGES)
        }
        return new_person_id

